"""
One-time codegen: export the constant tables of the original Python engine
(tuvi-app/) into web/src/lib/tuvi/data.ts so the TypeScript port uses the
exact same texts and tables.

Run from the repo root:  python3 web/scripts/gen_constants.py
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "tuvi-app"))

import lunar_calendar as lc  # noqa: E402
import tuvi_engine as te  # noqa: E402
import tuvi_analyzer as ta  # noqa: E402
import thai_at_engine as tae  # noqa: E402
import thai_at_analyzer as taa  # noqa: E402

out = {
    "CAN": lc.CAN,
    "CAN_SHORT": lc.CAN_SHORT,
    "CHI": lc.CHI,
    "CAN_HANH": lc.CAN_HANH,
    "CHI_HANH": lc.CHI_HANH,
    "NAP_AM": {f"{c}|{z}": list(v) for (c, z), v in lc.NAP_AM.items()},
    "PALACE_NAMES": te.PALACE_NAMES,
    "CUC_NAME": {str(k): list(v) for k, v in te.CUC_NAME.items()},
    "HANH_TO_CUC": te.HANH_TO_CUC,
    "SINH": te.SINH,
    "KHAC": te.KHAC,
    "STAR_HANH": te.STAR_HANH,
    "CAT_STARS": sorted(te.CAT_STARS),
    "BRIGHTNESS": te.BRIGHTNESS,
    "BRIGHTNESS_FULL": te.BRIGHTNESS_FULL,
    "TRANG_SINH_NAMES": te.TRANG_SINH_NAMES,
    "TRANG_SINH_START": {str(k): v for k, v in te.TRANG_SINH_START.items()},
    "TU_HOA": [list(te.TU_HOA[i]) for i in range(10)],
    "LOC_TON_POS": te.LOC_TON_POS,
    "KHOI_VIET": [list(te.KHOI_VIET[i]) for i in range(10)],
    "MENH_CHU": te.MENH_CHU,
    "THAN_CHU": te.THAN_CHU,
    "CHINH_TINH_DESC": ta.CHINH_TINH_DESC,
    "PALACE_DOMAIN": ta.PALACE_DOMAIN,
    "GOOD_STARS_MEANING": ta.GOOD_STARS_MEANING,
    "BAD_STARS_MEANING": ta.BAD_STARS_MEANING,
    "LUU_STAR_PALACE_EFFECT": {k: list(v) for k, v in ta.LUU_STAR_PALACE_EFFECT.items()},
    # ---- Thái Ất Thần Kinh ----
    "NAP_GIAP_CAN": {k: list(v) for k, v in lc.NAP_GIAP_CAN.items()},
    "NAP_GIAP_CHI": {k: list(v) for k, v in lc.NAP_GIAP_CHI.items()},
    "HANH_TO_THAI_AT_NUM": lc.HANH_TO_THAI_AT_NUM,
    "TA_PALACES_16": tae.PALACES_16_CLOCKWISE,
    "TA_CUNG_NUMBER_MAP": tae.CUNG_NUMBER_MAP,
    "TA_GIAN_THAN": sorted(tae.GIAN_THAN),
    "TA_GRID_POS": {k: list(v) for k, v in tae.GRID_POS.items()},
    "TA_PALACE_HANH": tae.PALACE_HANH,
    "TA_PALACE_KHI": tae.PALACE_KHI,
    "TA_PALACE_DIRECTION": tae.PALACE_DIRECTION,
    "TA_NHAN_MENH_12": tae.NHAN_MENH_12_PALACES,
    "TA_TOPIC_LABELS": taa.TOPIC_LABELS,
}

lines = [
    "// AUTO-GENERATED by web/scripts/gen_constants.py from the original Python engine.",
    "// Do not edit by hand; edit the generator or the source tables instead.",
    "",
]
for key, val in out.items():
    lines.append(f"export const {key} = {json.dumps(val, ensure_ascii=False, indent=2)} as const;")
    lines.append("")

dest = os.path.join(ROOT, "web", "src", "lib", "tuvi", "data.ts")
with open(dest, "w", encoding="utf-8") as f:
    f.write("\n".join(lines))
print("wrote", dest)
